/**
 * index.js — the Sharif University mark in the header, in three dimensions.
 *
 * WHAT IT IS
 * ----------
 * The round university logo, sitting in the top-right of the header at the
 * bar's own size, with two things happening to it:
 *
 *   the ring    a cyan arc sweeping clockwise around its rim, brightest at the
 *               head and trailing away behind — a meteor on a circular orbit.
 *               Pure CSS (see `.brandmark__ring` in fx.css); it costs nothing
 *               and it runs whatever else fails.
 *
 *   the mark    extruded and turned slowly about its vertical axis. Not a
 *               picture being spun: the navy artwork is real geometry with real
 *               thickness, traced out of the PNG by tools/trace-logo.py and
 *               extruded here, so the edges catch the light as it comes round.
 *
 * THE WHITE BACKGROUND HAS NO THICKNESS. That is deliberate and it is what
 * makes the object read as a mark standing off a plate rather than as a coin
 * with the design sunk into it. The plate is a flat disc; only the navy is
 * extruded.
 *
 * WHAT HAPPENS WITHOUT THREE.JS
 * -----------------------------
 * The flat mark turns about the same axis with a CSS transform, and the ring
 * carries on. It is the one place on this site where the two paths draw
 * genuinely different things, and the reason is honest: extruding a polygon
 * needs a triangulator, Three brings one, and hand-writing one for the fallback
 * would be a couple of hundred lines to slightly improve a 44-pixel logo. Both
 * paths turn the mark about its vertical axis, which is what the effect is.
 *
 * Without JavaScript at all, or with `prefers-reduced-motion`, it is the
 * ordinary <img> that was in the markup from the start, with its alt text and
 * its link to the university.
 */

import { el } from '../dom.js';
import { guardContext, loadThree } from '../fx/three.js';

/** Where the traced outlines live. Generated by tools/trace-logo.py. */
const OUTLINE_URL = 'assets/img/logos/logo.json';

/** Seconds for one full turn of the mark. */
const TURN_SECONDS = 14;

/** Thickness of the extrusion, as a fraction of the logo's width. */
const DEPTH = 0.075;

/** The mark's colour, from the artwork itself. */
const NAVY = 0x2e3192;

/**
 * How far the mark's outermost ring is opened up, in the same normalised units
 * the traced outlines use (the mark is one unit across after doubling).
 *
 * WHY THE RENDERER AND NOT THE TRACE
 * ----------------------------------
 * The artwork's outer ring is genuinely hairline: the tracer measures it at
 * about 0.022 units, half the width of the ring inside it. That is accurate,
 * and at the size a real crest is printed it is fine. At forty-four pixels it
 * is one pixel, and one navy pixel on white vanishes — the ring is only there
 * at all while the coin is turned far enough for the light to catch the side of
 * the extrusion, which is exactly the complaint: two rings while it moves, one
 * ring when it stops.
 *
 * So the ring is opened up here rather than in logo.json. tools/trace-logo.py's
 * job is to report what the artwork says; re-running it must not have to
 * remember a legibility decision made downstream of it. The outer edge grows
 * more than the inner shrinks, because there is more room outside — the disc
 * runs to 0.4962 and the ring's outer edge only to 0.4813, while the ring
 * inside it comes up to 0.4420.
 */
const RING_GROW_OUT = 0.011;
const RING_GROW_IN = 0.005;

/**
 * The reverse of the coin. Cool and slightly grey rather than pure white, so
 * the two faces are distinguishable as the logo turns — and so the reverse
 * reads as the back of an object rather than as a blank.
 */
const BACK_PLATE = 0xe4edf3;

/**
 * Open up the mark's outermost ring so it still reads face-on.
 *
 * The ring is found by measurement, not by index: it is the contour whose mean
 * radius is the largest, which is true of this artwork and stays true if the
 * tracer's ordering ever changes. Its outline is pushed out and its hole pulled
 * in, both along the radius from the mark's centre — the ring is very nearly
 * circular, so a radial offset thickens it evenly all the way round without
 * needing a real polygon offset.
 *
 * Everything else in the mark is returned untouched.
 *
 * @param {object} data  the parsed logo.json
 * @returns {object} the same shape, with one contour widened
 */
function thickenOuterRing(data) {
  const shapes = data.shapes || [];
  const meanRadius = (ring) =>
    ring.reduce((sum, [x, y]) => sum + Math.hypot(x, y), 0) / Math.max(1, ring.length);

  let outer = -1;
  let best = -Infinity;
  shapes.forEach((entry, i) => {
    const r = meanRadius(entry.outline || []);
    if (r > best) { best = r; outer = i; }
  });
  if (outer < 0) return data;

  /* Move a contour along its own radius. A point at the origin has no radius to
     move along, so it is left where it is rather than dividing by zero. */
  const offset = (ring, by) => ring.map(([x, y]) => {
    const r = Math.hypot(x, y);
    if (r < 1e-6) return [x, y];
    const k = (r + by) / r;
    return [x * k, y * k];
  });

  const entry = shapes[outer];
  const widened = {
    ...entry,
    outline: offset(entry.outline, RING_GROW_OUT),
    holes: (entry.holes || []).map((ring) => offset(ring, -RING_GROW_IN)),
  };

  return { ...data, shapes: shapes.map((s, i) => (i === outer ? widened : s)) };
}

/**
 * Build the header mark.
 *
 * @param {HTMLElement} host
 * @param {object} site  data/site.json — for the university's URL and name
 */
export async function mountBrandMark(host, site) {
  if (!host) return null;

  const affiliation = (site.affiliations || []).find((a) => /sharif/i.test(a.label || ''))
    || { url: 'http://www.en.sharif.edu/', label: 'Sharif University of Technology' };

  const poster = el('img', {
    class: 'brandmark__poster',
    src: 'assets/img/logos/logo.png',
    alt: affiliation.label,
    width: 44,
    height: 44,
    decoding: 'async',
  });

  const canvas = el('canvas', { class: 'brandmark__canvas', 'aria-hidden': 'true' });

  const link = el(
    'a',
    {
      class: 'brandmark__link',
      href: affiliation.url,
      target: '_blank',
      rel: 'noopener',
      title: affiliation.label,
    },
    el('span', { class: 'brandmark__ring', 'aria-hidden': 'true' }),
    canvas,
    poster,
  );

  const mark = el('div', { class: 'brandmark' }, link);
  host.replaceChildren(mark);

  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)');

  /* ---- the 3D path ------------------------------------------------------- */
  const THREE = await loadThree();
  if (!THREE) {
    // No library: the flat mark turns instead. The class is what starts it, so
    // nothing moves until we know we are not getting the real thing.
    mark.dataset.brandmark = 'css';
    return { renderer: 'css' };
  }

  let outlines;
  try {
    const response = await fetch(OUTLINE_URL);
    if (!response.ok) throw new Error(response.status + ' ' + response.statusText);
    outlines = thickenOuterRing(await response.json());
  } catch (err) {
    console.info('brandmark: no traced outlines, turning the flat mark instead.', err);
    mark.dataset.brandmark = 'css';
    return { renderer: 'css' };
  }

  let renderer;
  try {
    renderer = new THREE.WebGLRenderer({ canvas, antialias: true, alpha: true });
  } catch (err) {
    console.info('brandmark: no WebGL, turning the flat mark instead.', err);
    mark.dataset.brandmark = 'css';
    return { renderer: 'css' };
  }
  renderer.setClearColor(0x000000, 0);

  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(30, 1, 0.1, 20);
  camera.position.set(0, 0, 3.4);

  const group = new THREE.Group();
  scene.add(group);

  /* ---- the two plates ----------------------------------------------------
     Unlit on purpose. The front one is the logo's own white background, and
     white is what it has to look like — a lit material picks up the cyan rim
     light and the mark starts sitting on a pale blue coin.

     The back is a shade cooler than the front. It is a real coin: the reverse
     is not the obverse, and giving the two faces the same pure white made the
     back half of the turn look like a blank the artwork had fallen off.
     ---------------------------------------------------------------------- */
  const radius = outlines.disc.radius * 2;

  const plate = new THREE.Mesh(
    new THREE.CircleGeometry(radius, 64),
    new THREE.MeshBasicMaterial({ color: 0xffffff }),
  );
  plate.position.z = -0.002;
  group.add(plate);

  const back = new THREE.Mesh(
    new THREE.CircleGeometry(radius, 64),
    new THREE.MeshBasicMaterial({ color: BACK_PLATE }),
  );
  /* INSIDE the extrusion, just in front of its rear face — not behind it.
     "Behind the mark" is the wrong instinct here, because the whole point is
     that this plate is seen from the other side: once the coin has turned past
     ninety degrees the z axis is reversed, and a plate sitting behind the rear
     cap in the model is sitting *in front of* it on screen. That is what made
     the far half of the turn a blank disc. A plate a hair inside the span is
     hidden by the front plate from the front, and backs the artwork from the
     back, which is what a coin does. */
  back.position.z = -DEPTH * 2 + 0.012;
  back.rotation.y = Math.PI;
  group.add(back);

  /* ---- the mark: extruded ------------------------------------------------ */
  /* Coordinates arrive normalised to -0.5…0.5; doubling gives a mark one unit
     across, which is the scale the camera above is framed for. */
  const toShape = (ring) => {
    const shape = new THREE.Shape();
    ring.forEach(([x, y], i) => {
      if (i === 0) shape.moveTo(x * 2, y * 2);
      else shape.lineTo(x * 2, y * 2);
    });
    shape.closePath();
    return shape;
  };

  const shapes = outlines.shapes.map((entry) => {
    const shape = toShape(entry.outline);
    if (entry.holes) {
      shape.holes = entry.holes.map((ring) => {
        const path = new THREE.Path();
        ring.forEach(([x, y], i) => {
          if (i === 0) path.moveTo(x * 2, y * 2);
          else path.lineTo(x * 2, y * 2);
        });
        path.closePath();
        return path;
      });
    }
    return shape;
  });

  // One geometry for all 34 contours: Three triangulates each shape and merges
  // them, so the whole mark is a single mesh and a single draw call.
  const geometry = new THREE.ExtrudeGeometry(shapes, {
    depth: DEPTH * 2,
    bevelEnabled: false,
    curveSegments: 2,
  });
  geometry.translate(0, 0, -DEPTH * 2);

  const markMesh = new THREE.Mesh(
    geometry,
    new THREE.MeshStandardMaterial({ color: NAVY, roughness: 0.42, metalness: 0.12 }),
  );
  group.add(markMesh);

  /* ---- light ------------------------------------------------------------- */
  scene.add(new THREE.HemisphereLight(0xffffff, 0x404860, 2.1));
  const key = new THREE.DirectionalLight(0xffffff, 2.4);
  key.position.set(-1.4, 1.8, 2.6);
  scene.add(key);
  // A cyan fill from the left, so the turning edges pick up the site's accent
  // as they come round — the same colour as the ring orbiting outside them.
  const rim = new THREE.DirectionalLight(0x22d3ee, 1.5);
  rim.position.set(2.2, -0.6, 0.8);
  scene.add(rim);

  mark.dataset.brandmark = 'three';

  /* ---- the loop ---------------------------------------------------------- */
  let raf = 0;
  let last = 0;
  let running = false;
  let angle = 0;

  function size() {
    const rect = canvas.getBoundingClientRect();
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    renderer.setPixelRatio(dpr);
    renderer.setSize(rect.width || 44, rect.height || 44, false);
    camera.aspect = 1;
    camera.updateProjectionMatrix();
  }

  function draw() {
    group.rotation.y = angle;
    // A little tilt that follows the turn, so it reads as an object in space
    // rather than a cut-out on a turntable.
    group.rotation.x = Math.sin(angle) * 0.12;
    renderer.render(scene, camera);
  }

  function frame(now) {
    if (!running) return;
    const dt = last ? Math.min((now - last) / 1000, 0.05) : 0.016;
    last = now;
    angle += (Math.PI * 2 / TURN_SECONDS) * dt;
    draw();
    raf = requestAnimationFrame(frame);
  }

  function start() {
    if (running || reduced.matches) return;
    running = true;
    last = 0;
    raf = requestAnimationFrame(frame);
  }
  function stop() {
    running = false;
    cancelAnimationFrame(raf);
  }

  size();
  draw();

  const sync = () => (document.hidden || reduced.matches ? stop() : start());
  document.addEventListener('visibilitychange', sync);
  if (reduced.addEventListener) reduced.addEventListener('change', () => { sync(); draw(); });
  window.addEventListener('resize', () => { size(); draw(); }, { passive: true });

  // Turning a 44-pixel logo forever is not worth a wakeup on a page nobody is
  // looking at, so it stops with the tab.
  sync();

  /* If the phone takes the context away, go back to the flat mark rather than
     leaving a blank disc: `data-brandmark="css"` shows the poster again. */
  guardContext(canvas, {
    onLost() {
      stop();
      mark.dataset.brandmark = 'css';
    },
    onRestored() {
      mark.dataset.brandmark = 'three';
      size();
      draw();
      sync();
    },
  });

  return {
    renderer: 'three',
    shapes: outlines.shapes.length,
    triangles: geometry.attributes.position.count / 3,
    stop,
  };
}
